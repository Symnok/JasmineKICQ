def fill(lang, table):
    path = os.path.join(ROOT, "translations", "jasminekicq_%s.ts" % lang)
    tree = ET.parse(path)
    missing = []
    for msg in tree.getroot().iter("message"):
        src = msg.find("source").text or ""
        tr = msg.find("translation")
        text = table.get(src)
        if text is None:
            missing.append(src)
            continue
        tr.text = text
        if "type" in tr.attrib:
            del tr.attrib["type"]
    tree.write(path, encoding="utf-8", xml_declaration=True)
    # ET drops the DOCTYPE line lrelease is happy without; keep the file readable
    print("%s: %d missing" % (lang, len(missing)))
    for m in missing:
        print("   ", m)


